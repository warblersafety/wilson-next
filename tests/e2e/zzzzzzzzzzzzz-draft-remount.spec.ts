import { expect, test } from "@playwright/test";
import { productCapacityCase } from "../fixtures/product-capacity";
import { browserStateVersion } from "../../src/server/case/browser-state";
import { InMemoryCaseRepository } from "../../src/server/case/repository";
import { performJourneyAction } from "../../src/server/journey/service";
import { goTo, storedState } from "./draft4-helpers";
import { draftRecordKey } from "../../src/browser/ui-drafts";
import { draftOwnerHarnessHtml, readDraftOwner, remountDraftOwner, tryRestoreDraftOwner, rejectDraftAction } from "./ui-draft-harness";

test("actual components encode their inputs and retain cleared qualifier controls across owner remount and invalid restore", async ({ page }) => {
  const current = productCapacityCase();
  const repository = new InMemoryCaseRepository({ initialCase: current });
  const noModel = { propose: async (): Promise<never> => { throw new Error("No model calls in draft remount acceptance"); } };
  const snapshot = await performJourneyAction(repository, current.id, { action: "set-fact", target: "patient:patient:ageYears", value: { kind: "known", value: 57, qualifier: "approximately" } }, noModel);
  const state = { version: browserStateVersion, stage: snapshot.stage, case: (await repository.load(current.id))!, unrepresented: [] };
  const html = await draftOwnerHarnessHtml();
  await page.addInitScript(value => sessionStorage.setItem("wilson-journey-state-v2", JSON.stringify(value)), state);
  await page.route("**/__draft-owner-check", route => route.fulfill({ contentType: "text/html", body: html }));
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/__draft-owner-check");
  const age = page.locator('#case-card-patient [data-field="ageYears"]');
  const sex = page.locator('#case-card-patient [data-field="sex"]');
  await age.getByRole("button", { name: "Change", exact: true }).click();
  await age.getByLabel("New Age", { exact: true }).fill("58");
  await age.getByLabel("Uncertainty or context for Age", { exact: true }).fill("");
  await sex.getByRole("button", { name: "Change", exact: true }).click();
  await age.getByRole("button", { name: "Change", exact: true }).click();
  await expect(age.getByLabel("Uncertainty or context for Age", { exact: true })).toHaveValue("");
  await age.getByLabel("Uncertainty or context for Age", { exact: true }).fill("  ");
  await sex.getByRole("button", { name: "Change", exact: true }).click();
  await age.getByRole("button", { name: "Change", exact: true }).click();
  await expect(age.getByLabel("Uncertainty or context for Age", { exact: true })).toHaveValue("  ");
  await age.getByLabel("Uncertainty or context for Age", { exact: true }).fill("");
  await goTo(page, "Reporter details");
  await page.getByLabel("Reporter email", { exact: true }).fill("pending@example.test");
  await page.getByLabel("Date of this report", { exact: true }).fill("");
  await goTo(page, "Review details");
  await page.getByLabel("Clinical update", { exact: true }).fill(" Unsent words survive a real remount ");
  const key = draftRecordKey("card", JSON.stringify(["patient", "patient"]));
  await expect.poll(async () => (await readDraftOwner(page)).text).toMatchObject({ update: " Unsent words survive a real remount " });
  const encoded = await readDraftOwner(page);
  expect(Object.hasOwn(encoded.records as object, key)).toBe(true);
  const records = encoded.records as Record<string, { data: Record<string, unknown> }>;
  expect(records[key].data).toMatchObject({ editing: "ageYears", drafts: { ageYears: { kind: "known", value: 58 } }, qualifierControls: { ageYears: true } });
  expect((records[key].data.drafts as Record<string, { qualifier?: string }>).ageYears.qualifier).toBe("");
  expect(records[draftRecordKey("reporter", "case")].data).toMatchObject({ values: { email: "pending@example.test" }, reportDate: "" });
  const before = structuredClone(encoded);
  expect(await tryRestoreDraftOwner(page, { ...encoded, version: 2 })).toEqual({ ok: false, code: "incompatible" });
  expect(await tryRestoreDraftOwner(page, { ...encoded, records: { bad: {} } })).toEqual({ ok: false, code: "corrupt" });
  expect(await readDraftOwner(page)).toEqual(before);
  expect(await remountDraftOwner(page, encoded)).toEqual({ ok: true });
  await expect(page.getByLabel("Clinical update", { exact: true })).toHaveValue(" Unsent words survive a real remount ");
  await expect(age.getByLabel("New Age", { exact: true })).toHaveValue("58");
  await expect(age.getByLabel("Uncertainty or context for Age", { exact: true })).toHaveValue("");
  await age.getByLabel("Uncertainty or context for Age", { exact: true }).fill("still checking");
  await goTo(page, "Review & save");
  await expect(page.getByText("You have unsaved reporter details.", { exact: false })).toBeVisible();
  await goTo(page, "Reporter details");
  await expect(page.getByLabel("Reporter email", { exact: true })).toHaveValue("pending@example.test");
  await expect(page.getByLabel("Date of this report", { exact: true })).toHaveValue("");
  await rejectDraftAction(page);
  await expect(page.locator("main").getByRole("alert")).toContainText("Your current work is retained");
  await expect(page.getByLabel("Reporter email", { exact: true })).toHaveValue("pending@example.test");
  await page.getByLabel("Reporter email", { exact: true }).fill("still-pending@example.test");
  await expect(page.locator("main").getByRole("alert")).toHaveCount(0);
  expect(await storedState(page)).toEqual(state);
  expect(errors).toEqual([]);
});
